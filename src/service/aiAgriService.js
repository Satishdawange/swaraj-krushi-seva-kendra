// Helper: Normalize query for multilingual matching
function normalizeText(text) {
  return (text || "")
    .toLowerCase()
    .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// Crop detector helper for session context
export function detectCrop(text) {
  const q = normalizeText(text);
  if (!q) return null;

  if (
    q.includes("tamat") ||
    q.includes("tomet") ||
    q.includes("टोमॅटो") ||
    q.includes("टमाटे") ||
    q.includes("टमाटर")
  ) {
    return "tomato";
  }
  if (
    q.includes("draksh") ||
    q.includes("grape") ||
    q.includes("द्राक्ष") ||
    q.includes("द्राक्षे")
  ) {
    return "grapes";
  }
  if (
    q.includes("kand") ||
    q.includes("कांदा") ||
    q.includes("कांदे") ||
    q.includes("onion")
  ) {
    return "onion";
  }
  if (
    q.includes("mirch") ||
    q.includes("मिरची") ||
    q.includes("chili") ||
    q.includes("chilli") ||
    q.includes("चुरडा") ||
    q.includes("churda") ||
    q.includes("बोकड्या")
  ) {
    return "chilli";
  }
  if (
    q.includes("soyabean") ||
    q.includes("soybean") ||
    q.includes("सोयाबीन")
  ) {
    return "soybean";
  }
  if (
    q.includes("kapus") ||
    q.includes("cotton") ||
    q.includes("कापूस") ||
    q.includes("बोंडअळी")
  ) {
    return "cotton";
  }
  if (
    q.includes("makka") ||
    q.includes("maka") ||
    q.includes("मका") ||
    q.includes("corn")
  ) {
    return "corn";
  }
  if (
    q.includes("khat") ||
    q.includes("खत") ||
    q.includes("fertilizer") ||
    q.includes("युरिया") ||
    q.includes("dap") ||
    q.includes("19 19") ||
    q.includes("10 26")
  ) {
    return "fertilizer";
  }
  if (q.includes("tan") || q.includes("तण") || q.includes("weed")) {
    return "weed";
  }
  if (
    q.includes("ali") ||
    q.includes("aali") ||
    q.includes("illi") ||
    q.includes("अळी") ||
    q.includes("keed") ||
    q.includes("कीड")
  ) {
    return "pest";
  }
  return null;
}

