// Ask Gemini AI (with multi-turn history + image + audio/text prompt)
export async function askAgriAdvisor(
  promptText,
  imageBase64 = null,
  mimeType = "image/jpeg",
  context = {},
  history = [],
) {
  // Check if query contains a mobile number - immediately provide personalized bill & usage lookup
  const mobileMatch = promptText.match(/\b([6-9]\d{9})\b/);
  if (mobileMatch) {
    return await getFallbackAgriResponse(promptText, context);
  }

  const apiKey = import.meta.env.VITE_GEMINI_API_KEY;

  // If no Gemini key is provided, use the smart local agri advisor seamlessly
  if (!apiKey || apiKey.trim() === "" || apiKey === "YOUR_GEMINI_API_KEY") {
    await new Promise((resolve) => setTimeout(resolve, 400));
    return await getFallbackAgriResponse(promptText, context);
  }

  try {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;

    const contents = [];

    // Attach previous conversation history if active in session
    if (Array.isArray(history) && history.length > 0) {
      history.forEach((turn) => {
        contents.push({
          role: turn.sender === "bot" ? "model" : "user",
          parts: [{ text: turn.text }],
        });
      });
    }

    // Current turn
    const currentParts = [];
    let promptWithContext = promptText;
    if (context.activeCrop) {
      promptWithContext = `[संदर्भ पीक: ${context.activeCrop}]\n${promptText}`;
    }
    currentParts.push({ text: promptWithContext });

    if (imageBase64) {
      currentParts.push({
        inlineData: {
          mimeType: mimeType || "image/jpeg",
          data: imageBase64,
        },
      });
    }

    contents.push({
      role: "user",
      parts: currentParts,
    });

    const response = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        systemInstruction: {
          parts: [{ text: SYSTEM_INSTRUCTION }],
        },
        contents: contents,
      }),
    });

    if (!response.ok) {
      console.warn("Gemini API call failed, using smart local advisor");
      return await getFallbackAgriResponse(promptText, context);
    }

    const data = await response.json();
    let reply = data.candidates?.[0]?.content?.parts?.[0]?.text;

    // Clean up any stray markdown asterisks if Gemini still includes them
    if (reply) {
      reply = reply.replace(/\*\*/g, "").replace(/###\s*/g, "");
    }

    return reply || (await getFallbackAgriResponse(promptText, context));
  } catch (error) {
    console.error(
      "Error connecting to Gemini, falling back to local advisor:",
      error,
    );
    return await getFallbackAgriResponse(promptText, context);
  }
}
